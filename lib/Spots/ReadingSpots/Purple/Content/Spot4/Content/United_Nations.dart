// ── UN Globe Icon painter ─────────────────────────────────────────────────────

class _UNGlobeIconPainter extends CustomPainter {
  @override
  void paint(Canvas canvas, Size size) {
    final double s = size.width / 24;

    final mainPaint = Paint()
      ..color = const Color(0xFFD8B4FE)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.4
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;

    final linePaint = Paint()
      ..color = const Color(0xFFC4B5FD).withOpacity(0.5)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 0.9
      ..strokeCap = StrokeCap.round;

    final olivePaint = Paint()
      ..color = const Color(0xFFA78BFA).withOpacity(0.8)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.0
      ..strokeCap = StrokeCap.round;

    // Globe outline
    canvas.drawCircle(Offset(12 * s, 12 * s), 9 * s, mainPaint);

    // Equator
    canvas.drawLine(
      Offset(3 * s, 12 * s),
      Offset(21 * s, 12 * s),
      linePaint,
    );

    // Upper latitude
    final upperLat = Path();
    upperLat.moveTo(4 * s, 8.5 * s);
    upperLat.quadraticBezierTo(12 * s, 6.5 * s, 20 * s, 8.5 * s);
    canvas.drawPath(
        upperLat, linePaint..color = const Color(0xFFC4B5FD).withOpacity(0.4));

    // Lower latitude
    final lowerLat = Path();
    lowerLat.moveTo(4 * s, 15.5 * s);
    lowerLat.quadraticBezierTo(12 * s, 17.5 * s, 20 * s, 15.5 * s);
    canvas.drawPath(lowerLat, linePaint);

    // Left meridian
    final leftMeridian = Path();
    leftMeridian.moveTo(12 * s, 3 * s);
    leftMeridian.quadraticBezierTo(9 * s, 7.5 * s, 9 * s, 12 * s);
    leftMeridian.quadraticBezierTo(9 * s, 16.5 * s, 12 * s, 21 * s);
    canvas.drawPath(leftMeridian, linePaint);

    // Right meridian
    final rightMeridian = Path();
    rightMeridian.moveTo(12 * s, 3 * s);
    rightMeridian.quadraticBezierTo(15 * s, 7.5 * s, 15 * s, 12 * s);
    rightMeridian.quadraticBezierTo(15 * s, 16.5 * s, 12 * s, 21 * s);
    canvas.drawPath(rightMeridian, linePaint);

    // Left olive branch
    final leftBranch = Path();
    leftBranch.moveTo(5 * s, 14 * s);
    leftBranch.quadraticBezierTo(4 * s, 11 * s, 6 * s, 10 * s);
    canvas.drawPath(leftBranch, olivePaint);

    final leftLeaf1 = Path();
    leftLeaf1.moveTo(5 * s, 13 * s);
    leftLeaf1.quadraticBezierTo(4.5 * s, 11.5 * s, 6.5 * s, 11 * s);
    canvas.drawPath(leftLeaf1, olivePaint);

    final leftLeaf2 = Path();
    leftLeaf2.moveTo(5.5 * s, 11.5 * s);
    leftLeaf2.quadraticBezierTo(5 * s, 10 * s, 7.5 * s, 10 * s);
    canvas.drawPath(leftLeaf2, olivePaint);

    // Right olive branch
    final rightBranch = Path();
    rightBranch.moveTo(19 * s, 14 * s);
    rightBranch.quadraticBezierTo(20 * s, 11 * s, 18 * s, 10 * s);
    canvas.drawPath(rightBranch, olivePaint);

    final rightLeaf1 = Path();
    rightLeaf1.moveTo(19 * s, 13 * s);
    rightLeaf1.quadraticBezierTo(19.5 * s, 11.5 * s, 17.5 * s, 11 * s);
    canvas.drawPath(rightLeaf1, olivePaint);

    final rightLeaf2 = Path();
    rightLeaf2.moveTo(18.5 * s, 11.5 * s);
    rightLeaf2.quadraticBezierTo(19 * s, 10 * s, 16.5 * s, 10 * s);
    canvas.drawPath(rightLeaf2, olivePaint);
  }

  @override
  bool shouldRepaint(_UNGlobeIconPainter old) => false;
}

// ── Particle painter ──────────────────────────────────────────────────────────

class _ParticlePainter extends CustomPainter {
  final double progress;

  static final List<_Particle> _particles = List.generate(20, (i) {
    return _Particle(
      x: (i * 137.508) % 1.0,
      y: (i * 97.3) % 1.0,
      radius: 1.2 + (i % 4) * 0.8,
      speed: 0.04 + (i % 5) * 0.018,
      phase: (i * 0.43) % 1.0,
    );
  });

  _ParticlePainter(this.progress);

  @override
  void paint(Canvas canvas, Size size) {
    final paint = Paint()..color = const Color(0xFFA855F7).withOpacity(0.28);

    for (final p in _particles) {
      final dy = (p.y + progress * p.speed + p.phase) % 1.0;
      final dx = p.x + 0.03 * math.sin(progress * math.pi * 2 + p.phase * 6);
      canvas.drawCircle(
        Offset(dx * size.width, dy * size.height),
        p.radius,
        paint,
      );
    }
  }

  @override
  bool shouldRepaint(_ParticlePainter old) => true;
}

class _Particle {
  final double x, y, radius, speed, phase;
  const _Particle({
    required this.x,
    required this.y,
    required this.radius,
    required this.speed,
    required this.phase,
  });
}

