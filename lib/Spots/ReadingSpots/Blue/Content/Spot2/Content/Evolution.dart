class _DNAIconPainter extends CustomPainter {
  @override
  void paint(Canvas canvas, Size size) {
    final w = size.width;
    final h = size.height;

    final strokeL = Paint()
      ..color = Colors.white.withOpacity(0.9)
      ..strokeWidth = 2.5
      ..style = PaintingStyle.stroke
      ..strokeCap = StrokeCap.round;
    final strokeR = Paint()
      ..color = Colors.white.withOpacity(0.7)
      ..strokeWidth = 2.5
      ..style = PaintingStyle.stroke
      ..strokeCap = StrokeCap.round;
    final rungPaint = Paint()
      ..color = Colors.white.withOpacity(0.55)
      ..strokeWidth = 1.5
      ..strokeCap = StrokeCap.round
      ..style = PaintingStyle.stroke;
    final dotPaint = Paint()
      ..color = Colors.white.withOpacity(0.8)
      ..style = PaintingStyle.fill;

    final cx = w / 2;
    final amplitude = w * 0.3;
    const steps = 40;

    final pathL = Path();
    final pathR = Path();

    for (int i = 0; i <= steps; i++) {
      final t = i / steps;
      final y = t * h;
      final xL = cx - amplitude * sin(t * 2 * pi);
      final xR = cx + amplitude * sin(t * 2 * pi);
      i == 0 ? pathL.moveTo(xL, y) : pathL.lineTo(xL, y);
      i == 0 ? pathR.moveTo(xR, y) : pathR.lineTo(xR, y);
    }

    canvas.drawPath(pathL, strokeL);
    canvas.drawPath(pathR, strokeR);

    // Rungs at cross points
    final rungTs = [0.15, 0.38, 0.62, 0.85];
    for (final t in rungTs) {
      final y = t * h;
      final xL = cx - amplitude * sin(t * 2 * pi);
      final xR = cx + amplitude * sin(t * 2 * pi);
      canvas.drawLine(Offset(xL, y), Offset(xR, y), rungPaint);
    }

    // End dots
    canvas.drawCircle(Offset(cx - amplitude * sin(0), 0), 2.5, dotPaint);
    canvas.drawCircle(Offset(cx + amplitude * sin(0), 0), 2.5,
        dotPaint..color = Colors.white.withOpacity(0.6));
    canvas.drawCircle(Offset(cx + amplitude * sin(2 * pi), h), 2.5,
        dotPaint..color = Colors.white.withOpacity(0.8));
    canvas.drawCircle(Offset(cx - amplitude * sin(2 * pi), h), 2.5,
        dotPaint..color = Colors.white.withOpacity(0.6));
  }

  @override
  bool shouldRepaint(_DNAIconPainter old) => false;
}

