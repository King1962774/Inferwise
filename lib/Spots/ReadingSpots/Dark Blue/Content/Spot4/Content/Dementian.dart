// ── Caring Hands Icon painter ─────────────────────────────────────────────────

class _CaringHandsIconPainter extends CustomPainter {
  @override
  void paint(Canvas canvas, Size size) {
    final double s = size.width / 24;

    final mainPaint = Paint()
      ..color = const Color(0xFFD8B4FE)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.3
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;

    final accentPaint = Paint()
      ..color = const Color(0xFFC4B5FD)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.3
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;

    final dotPaint = Paint()
      ..color = const Color(0xFFC4B5FD).withOpacity(0.55)
      ..style = PaintingStyle.fill;

    // Heart
    final heartPath = Path();
    heartPath.moveTo(12 * s, 8.5 * s);
    heartPath.cubicTo(
      12 * s, 8.5 * s,
      10 * s, 6 * s,
      8 * s, 7 * s,
    );
    heartPath.cubicTo(
      6 * s, 8 * s,
      5.5 * s, 10.5 * s,
      7.5 * s, 12.5 * s,
    );
    heartPath.lineTo(12 * s, 17 * s);
    heartPath.lineTo(16.5 * s, 12.5 * s);
    heartPath.cubicTo(
      18.5 * s, 10.5 * s,
      18 * s, 8 * s,
      16 * s, 7 * s,
    );
    heartPath.cubicTo(
      14 * s, 6 * s,
      12 * s, 8.5 * s,
      12 * s, 8.5 * s,
    );
    canvas.drawPath(heartPath, mainPaint);

    // Left arm/hand
    final leftArm = Path();
    leftArm.moveTo(4 * s, 17 * s);
    leftArm.quadraticBezierTo(5 * s, 15 * s, 7 * s, 15 * s);
    leftArm.lineTo(9 * s, 15 * s);
    canvas.drawPath(leftArm, accentPaint);
    canvas.drawLine(
      Offset(4 * s, 17 * s),
      Offset(4 * s, 20 * s),
      accentPaint,
    );

    // Right arm/hand
    final rightArm = Path();
    rightArm.moveTo(20 * s, 17 * s);
    rightArm.quadraticBezierTo(19 * s, 15 * s, 17 * s, 15 * s);
    rightArm.lineTo(15 * s, 15 * s);
    canvas.drawPath(rightArm, accentPaint);
    canvas.drawLine(
      Offset(20 * s, 17 * s),
      Offset(20 * s, 20 * s),
      accentPaint,
    );

    // Warmth dots
    canvas.drawCircle(Offset(5 * s, 8 * s), 0.6 * s, dotPaint);
    canvas.drawCircle(Offset(19 * s, 8 * s), 0.6 * s, dotPaint);
    canvas.drawCircle(Offset(12 * s, 4 * s), 0.6 * s, dotPaint);
  }

  @override
  bool shouldRepaint(_CaringHandsIconPainter old) => false;
}

// ── Particle painter ──────────────────────────────────────────────────────────

class _ParticlePainter extends CustomPainter {
  final double progress;

  static final List<_Particle> _particles = List.generate(20, (i) {
    return _Particle(
      x: (i * 137.508) % 1.0,
      y: (i * 97.3) % 1.0,
      radius: 1.2 + (i % 4) * 0.8,
      speed: 0.04 + (i % 5) * 0.018,
      phase: (i * 0.43) % 1.0,
    );
  });

  _ParticlePainter(this.progress);

  @override
  void paint(Canvas canvas, Size size) {
    final paint = Paint()
      ..color = const Color(0xFFA855F7).withOpacity(0.28);

    for (final p in _particles) {
      final dy = (p.y + progress * p.speed + p.phase) % 1.0;
      final dx =
          p.x + 0.03 * math.sin(progress * math.pi * 2 + p.phase * 6);
      canvas.drawCircle(
        Offset(dx * size.width, dy * size.height),
        p.radius,
        paint,
      );
    }
  }

  @override
  bool shouldRepaint(_ParticlePainter old) => true;
}

class _Particle {
  final double x, y, radius, speed, phase;
  const _Particle({
    required this.x,
    required this.y,
    required this.radius,
    required this.speed,
    required this.phase,
  });
}

