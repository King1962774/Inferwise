class _MedicalCrossPainter extends CustomPainter {
  final double pulseProgress;

  const _MedicalCrossPainter({required this.pulseProgress});

  @override
  void paint(Canvas canvas, Size size) {
    final w = size.width;
    final h = size.height;

    // Cruz médica
    final crossPaint = Paint()
      ..color = Colors.white.withOpacity(0.88)
      ..style = PaintingStyle.fill;

    canvas.drawRRect(
      RRect.fromRectAndRadius(
        Rect.fromLTWH(w * 0.36, h * 0.07, w * 0.28, h * 0.86),
        const Radius.circular(4),
      ),
      crossPaint,
    );
    canvas.drawRRect(
      RRect.fromRectAndRadius(
        Rect.fromLTWH(w * 0.07, h * 0.39, w * 0.86, h * 0.22),
        const Radius.circular(4),
      ),
      crossPaint,
    );

    // Línea de pulso ECG animada encima de la cruz
    // Los puntos definen la onda cardíaca a lo largo del eje horizontal
    final pulsePoints = [
      Offset(w * 0.04, h * 0.5),
      Offset(w * 0.20, h * 0.5),
      Offset(w * 0.30, h * 0.26),
      Offset(w * 0.38, h * 0.74),
      Offset(w * 0.46, h * 0.36),
      Offset(w * 0.54, h * 0.58),
      Offset(w * 0.62, h * 0.5),
      Offset(w * 0.80, h * 0.5),
      Offset(w * 0.96, h * 0.5),
    ];

    // Construimos el path completo
    final fullPath = Path()..moveTo(pulsePoints[0].dx, pulsePoints[0].dy);
    for (int i = 1; i < pulsePoints.length; i++) {
      fullPath.lineTo(pulsePoints[i].dx, pulsePoints[i].dy);
    }

    // Calculamos longitud total aproximada para dash trick
    final totalLength = _pathLength(pulsePoints);
    final drawn = totalLength * pulseProgress;

    // Opacidad que sube y baja con el ciclo
    final lineOpacity = pulseProgress < 0.5
        ? pulseProgress * 2
        : (1.0 - pulseProgress) * 2;

    final pulsePaint = Paint()
      ..color = const Color(0xFF1E643C).withOpacity(0.55 + lineOpacity * 0.25)
      ..strokeWidth = 2.0
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round
      ..style = PaintingStyle.stroke;

    // Dibujamos solo la porción animada
    _drawPartialPath(canvas, pulsePoints, drawn, pulsePaint);
  }

  double _pathLength(List<Offset> points) {
    double total = 0;
    for (int i = 1; i < points.length; i++) {
      total += (points[i] - points[i - 1]).distance;
    }
    return total;
  }

  void _drawPartialPath(
      Canvas canvas, List<Offset> points, double drawn, Paint paint) {
    if (drawn <= 0) return;
    final path = Path()..moveTo(points[0].dx, points[0].dy);
    double remaining = drawn;

    for (int i = 1; i < points.length; i++) {
      final seg = (points[i] - points[i - 1]).distance;
      if (remaining <= 0) break;
      if (remaining >= seg) {
        path.lineTo(points[i].dx, points[i].dy);
        remaining -= seg;
      } else {
        final t = remaining / seg;
        final px = points[i - 1].dx + (points[i].dx - points[i - 1].dx) * t;
        final py = points[i - 1].dy + (points[i].dy - points[i - 1].dy) * t;
        path.lineTo(px, py);
        break;
      }
    }
    canvas.drawPath(path, paint);
  }

  @override
  bool shouldRepaint(_MedicalCrossPainter old) =>
      old.pulseProgress != pulseProgress;
}

