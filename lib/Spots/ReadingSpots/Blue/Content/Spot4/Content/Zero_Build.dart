// ── Net Zero Building Icon painter ────────────────────────────────────────────

class _NetZeroIconPainter extends CustomPainter {
  @override
  void paint(Canvas canvas, Size size) {
    final double s = size.width / 24;

    final mainPaint = Paint()
      ..color = const Color(0xFFD8B4FE)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.4
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;

    final accentPaint = Paint()
      ..color = const Color(0xFFA78BFA)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.1
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;

    final dotPaint = Paint()
      ..color = const Color(0xFFC4B5FD).withOpacity(0.55)
      ..style = PaintingStyle.fill;

    // Building body
    final buildingPath = Path();
    buildingPath.addRRect(RRect.fromRectAndRadius(
      Rect.fromLTWH(4 * s, 8 * s, 10 * s, 13 * s),
      const Radius.circular(0.5),
    ));
    canvas.drawPath(buildingPath, mainPaint);

    // Roof line
    canvas.drawLine(
      Offset(3 * s, 8 * s),
      Offset(15 * s, 8 * s),
      mainPaint,
    );

    // Windows
    final windowPaint = Paint()
      ..color = const Color(0xFFC4B5FD)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.1;

    for (final pos in [
      Rect.fromLTWH(6 * s, 10.5 * s, 2 * s, 2 * s),
      Rect.fromLTWH(10 * s, 10.5 * s, 2 * s, 2 * s),
      Rect.fromLTWH(6 * s, 14 * s, 2 * s, 2 * s),
      Rect.fromLTWH(10 * s, 14 * s, 2 * s, 2 * s),
    ]) {
      canvas.drawRRect(
        RRect.fromRectAndRadius(pos, const Radius.circular(0.3)),
        windowPaint,
      );
    }

    // Door
    canvas.drawRRect(
      RRect.fromRectAndRadius(
        Rect.fromLTWH(8 * s, 18 * s, 2.5 * s, 3 * s),
        const Radius.circular(0.3),
      ),
      mainPaint,
    );

    // Leaf growing on right side of building
    final leafPath = Path();
    leafPath.moveTo(16 * s, 17 * s);
    leafPath.quadraticBezierTo(19 * s, 14 * s, 18 * s, 10 * s);
    leafPath.quadraticBezierTo(15 * s, 12 * s, 16 * s, 17 * s);
    canvas.drawPath(leafPath, accentPaint);

    // Leaf tendril
    final tendrilPath = Path();
    tendrilPath.moveTo(16 * s, 17 * s);
    tendrilPath.quadraticBezierTo(20 * s, 17 * s, 21 * s, 13 * s);
    canvas.drawPath(tendrilPath, accentPaint);

    // Zero carbon arc above building
    final arcPath = Path();
    arcPath.moveTo(6 * s, 6 * s);
    arcPath.quadraticBezierTo(9 * s, 3 * s, 12 * s, 6 * s);
    canvas.drawPath(arcPath, accentPaint..color = const Color(0xFFC4B5FD).withOpacity(0.6));

    // Small dot above arc
    canvas.drawCircle(Offset(9 * s, 4.5 * s), 0.7 * s, dotPaint);
  }

  @override
  bool shouldRepaint(_NetZeroIconPainter old) => false;
}

// ── Particle painter ──────────────────────────────────────────────────────────

class _ParticlePainter extends CustomPainter {
  final double progress;

  static final List<_Particle> _particles = List.generate(20, (i) {
    return _Particle(
      x: (i * 137.508) % 1.0,
      y: (i * 97.3) % 1.0,
      radius: 1.2 + (i % 4) * 0.8,
      speed: 0.04 + (i % 5) * 0.018,
      phase: (i * 0.43) % 1.0,
    );
  });

  _ParticlePainter(this.progress);

  @override
  void paint(Canvas canvas, Size size) {
    final paint = Paint()
      ..color = const Color(0xFFA855F7).withOpacity(0.28);

    for (final p in _particles) {
      final dy = (p.y + progress * p.speed + p.phase) % 1.0;
      final dx =
          p.x + 0.03 * math.sin(progress * math.pi * 2 + p.phase * 6);
      canvas.drawCircle(
        Offset(dx * size.width, dy * size.height),
        p.radius,
        paint,
      );
    }
  }

  @override
  bool shouldRepaint(_ParticlePainter old) => true;
}

class _Particle {
  final double x, y, radius, speed, phase;
  const _Particle({
    required this.x,
    required this.y,
    required this.radius,
    required this.speed,
    required this.phase,
  });
}

