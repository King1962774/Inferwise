// ─── Spider Web + Orbit painter ───────────────────────────────────────
class _SpiderWebPainter extends CustomPainter {
  final double innerGlow, outerGlow, spiderGlow;
  final double webOpacity, webScale, webRingOpacity;
  final double orbit1T, orbit2T, orbit3T;
  final List<List<double>> orbitStars;
  final List<double> spokeAngles;
  final List<double> webRings;

  const _SpiderWebPainter({
    required this.innerGlow,      required this.outerGlow,
    required this.spiderGlow,     required this.webOpacity,
    required this.webScale,       required this.webRingOpacity,
    required this.orbit1T,        required this.orbit2T,
    required this.orbit3T,        required this.orbitStars,
    required this.spokeAngles,    required this.webRings,
  });

  @override
  void paint(Canvas canvas, Size size) {
    final cx  = size.width  / 2;
    final cy  = size.height / 2;
    final scl = size.width  / 180;

    // ── AMBIENT GLOWS ─────────────────────────────────────────────
    canvas.drawCircle(Offset(cx, cy), 82 * scl,
        Paint()..shader = RadialGradient(colors: [
          const Color(0xFF4080FF).withOpacity(outerGlow),
          const Color(0xFF4080FF).withOpacity(0),
        ]).createShader(Rect.fromCircle(
            center: Offset(cx, cy), radius: 82 * scl)));

    canvas.drawCircle(Offset(cx, cy), 55 * scl,
        Paint()..shader = RadialGradient(colors: [
          const Color(0xFF2060FF).withOpacity(innerGlow),
          const Color(0xFF1040CC).withOpacity(innerGlow * .15),
          const Color(0xFF1040CC).withOpacity(0),
        ], stops: const [0.0, .55, 1.0]).createShader(Rect.fromCircle(
            center: Offset(cx, cy), radius: 55 * scl)));

    // ── SPIDER WEB ────────────────────────────────────────────────
    canvas.save();
    canvas.translate(cx, cy);
    canvas.scale(webScale);

    // Spokes
    final spokePaint = Paint()
      ..color = const Color(0xFF78AAF0).withOpacity(webOpacity)
      ..strokeWidth = scl * .9
      ..strokeCap = StrokeCap.round;

    final maxSpokeR = 52 * scl;
    for (final deg in spokeAngles) {
      final rad = deg * math.pi / 180;
      canvas.drawLine(
        Offset.zero,
        Offset(math.sin(rad) * maxSpokeR, -math.cos(rad) * maxSpokeR),
        spokePaint,
      );
    }

    // Concentric rings
    final ringPaint = Paint()
      ..color = const Color(0xFF64A0FF).withOpacity(webRingOpacity)
      ..strokeWidth = scl * .9
      ..style = PaintingStyle.stroke;

    for (final r in webRings) {
      canvas.drawCircle(Offset.zero, r * scl, ringPaint);
    }

    canvas.restore();

    // ── ORBITING STARS ────────────────────────────────────────────
    for (final os in orbitStars) {
      final ring      = os[0].toInt();
      final offsetDeg = os[1];
      final radius    = os[2] * scl;
      final starR     = os[3] * scl;
      final t = ring == 1 ? orbit1T : ring == 2 ? orbit2T : orbit3T;

      final tiltRad = ring == 2 ?  20 * math.pi / 180
                    : ring == 3 ? -30 * math.pi / 180
                    : 0.0;

      final angleRad = (offsetDeg + t * 360) * math.pi / 180;
      final rawX = math.cos(angleRad) * radius;
      final rawY = math.sin(angleRad) * radius * math.cos(tiltRad);
      final pop  = .7 + .3 * math.sin(angleRad * 2 + t * math.pi * 2).abs();

      canvas.drawCircle(
        Offset(cx + rawX, cy + rawY),
        starR * pop,
        Paint()..color = const Color(0xFF8CC8FF).withOpacity(.75 * pop),
      );

      if ((ring == 1 || ring == 2) && offsetDeg == 0) {
        final arm = starR * 1.8 * pop;
        final sx = cx + rawX; final sy = cy + rawY;
        final sp = Paint()
          ..color = const Color(0xFFB4E0FF)
              .withOpacity(ring == 1 ? .78 * pop : .65 * pop)
          ..strokeWidth = 1.0
          ..strokeCap = StrokeCap.round;
        canvas.drawLine(Offset(sx - arm, sy), Offset(sx + arm, sy), sp);
        canvas.drawLine(Offset(sx, sy - arm), Offset(sx, sy + arm), sp);
      }
    }

    // ── SPIDER ICON GLOW ──────────────────────────────────────────
    canvas.drawCircle(Offset(cx, cy), 44 * scl,
        Paint()..shader = RadialGradient(colors: [
          const Color(0xFF2858C8).withOpacity(spiderGlow * .50),
          const Color(0xFF2858C8).withOpacity(0),
        ]).createShader(Rect.fromCircle(
            center: Offset(cx, cy), radius: 44 * scl)));
  }

  @override
  bool shouldRepaint(covariant _SpiderWebPainter o) =>
      o.innerGlow      != innerGlow      || o.outerGlow      != outerGlow      ||
      o.spiderGlow     != spiderGlow     || o.webOpacity     != webOpacity     ||
      o.webScale       != webScale       || o.webRingOpacity != webRingOpacity ||
      o.orbit1T        != orbit1T        || o.orbit2T        != orbit2T        ||
      o.orbit3T        != orbit3T;
}

// ─── Nebula ───────────────────────────────────────────────────────────
class _SpiderNebula extends StatefulWidget {
  final Color color;
  final Alignment alignment;
  final double size;
  final int delay;
  const _SpiderNebula({required this.color, required this.alignment,
      required this.size, this.delay = 0});
  @override State<_SpiderNebula> createState() => _SpiderNebulaState();
}
class _SpiderNebulaState extends State<_SpiderNebula>
    with SingleTickerProviderStateMixin {
  late AnimationController _c;
  late Animation<double> _opacity, _scale;
  @override
  void initState() {
    super.initState();
    _c = AnimationController(
        duration: const Duration(milliseconds: 9000), vsync: this)
      ..repeat(reverse: true);
    _opacity = Tween<double>(begin: .08, end: .18).animate(
        CurvedAnimation(parent: _c, curve: Curves.easeInOut));
    _scale   = Tween<double>(begin: 1.0, end: 1.07).animate(
        CurvedAnimation(parent: _c, curve: Curves.easeInOut));
    if (widget.delay > 0) {
      _c.value = (widget.delay / 9000.0).clamp(0.0, 1.0);
    }
  }
  @override void dispose() { _c.dispose(); super.dispose(); }
  @override
  Widget build(BuildContext context) {
    return Positioned.fill(
      child: Align(
        alignment: widget.alignment,
        child: AnimatedBuilder(
          animation: _c,
          builder: (_, __) => Opacity(
            opacity: _opacity.value,
            child: Transform.scale(
              scale: _scale.value,
              child: Container(
                width: widget.size, height: widget.size * .6,
                decoration: BoxDecoration(
                  borderRadius: BorderRadius.circular(widget.size),
                  gradient: RadialGradient(colors: [
                    widget.color.withOpacity(1),
                    widget.color.withOpacity(0),
                  ]),
                ),
              ),
            ),
          ),
        ),
      ),
    );
  }
}

// ─── Floating particle ────────────────────────────────────────────────
class _SpiderParticle extends StatefulWidget {
  final double xF, yF, sz;
  final int shape, durMs, delayMs;
  const _SpiderParticle({required this.xF, required this.yF, required this.sz,
      required this.shape, required this.durMs, required this.delayMs});
  @override State<_SpiderParticle> createState() => _SpiderParticleState();
}
class _SpiderParticleState extends State<_SpiderParticle>
    with SingleTickerProviderStateMixin {
  late AnimationController _c;
  late Animation<Offset> _pos;
  static const _offsets = [
    Offset(-8,-12), Offset(9,-8), Offset(-6,10), Offset(8,8),
  ];
  @override
  void initState() {
    super.initState();
    _c = AnimationController(
        duration: Duration(milliseconds: widget.durMs), vsync: this)
      ..repeat(reverse: true);
    _pos = Tween<Offset>(
      begin: Offset.zero,
      end: _offsets[widget.shape % _offsets.length],
    ).animate(CurvedAnimation(parent: _c, curve: Curves.easeInOut));
    if (widget.delayMs > 0) {
      _c.value = (widget.delayMs / widget.durMs).clamp(0.0, 1.0);
    }
  }
  @override void dispose() { _c.dispose(); super.dispose(); }
  @override
  Widget build(BuildContext context) {
    final s = MediaQuery.of(context).size;
    return Positioned(
      left: widget.xF * s.width,
      top:  widget.yF * s.height,
      child: AnimatedBuilder(
        animation: _c,
        builder: (_, __) => Transform.translate(
          offset: _pos.value,
