// ── Fondo animado ─────────────────────────────────────────────────────────

class _AnimatedBackground extends StatelessWidget {
  final AnimationController floatController;
  final AnimationController bgController;
  final Size size;

  const _AnimatedBackground({
    required this.floatController,
    required this.bgController,
    required this.size,
  });

  @override
  Widget build(BuildContext context) {
    return AnimatedBuilder(
      animation: Listenable.merge([floatController, bgController]),
      builder: (_, __) => CustomPaint(
        size: size,
        painter: _BackgroundPainter(
          floatValue: floatController.value,
          bgValue: bgController.value,
        ),
      ),
    );
  }
}

class _BackgroundPainter extends CustomPainter {
  final double floatValue;
  final double bgValue;

  _BackgroundPainter({required this.floatValue, required this.bgValue});

  static const Color _darkGreen = Color(0xFF123D23);
  static const Color _midGreen = Color(0xFF1A5C35);
  static const Color _lightGreen = Color(0xFF2D7A4F);

  @override
  void paint(Canvas canvas, Size size) {
    final rng = Random(66);

    // Gradiente de fondo
    final bgRect = Rect.fromLTWH(0, 0, size.width, size.height);
    final bgPaint = Paint()
      ..shader = LinearGradient(
        begin: Alignment.topLeft,
        end: Alignment.bottomRight,
        colors: [_lightGreen, _midGreen, _darkGreen],
        stops: [0.0, 0.45 + 0.05 * sin(bgValue * 2 * pi), 1.0],
        transform: GradientRotation(pi * (0.44 + 0.04 * sin(bgValue * pi))),
      ).createShader(bgRect);
    canvas.drawRect(bgRect, bgPaint);

    // Blobs
    _drawBlob(
        canvas,
        Offset(size.width * 0.2 + 6 * sin(bgValue * 2 * pi),
            size.height * 0.15 - 8 * cos(bgValue * 2 * pi)),
        220,
        Colors.white.withOpacity(0.04 + 0.02 * sin(bgValue * 2 * pi)));
    _drawBlob(canvas, Offset(size.width * 0.85, size.height * 0.85), 180,
        Colors.black.withOpacity(0.12 + 0.04 * cos(bgValue * 2 * pi)));
    _drawBlob(canvas, Offset(size.width * 0.1, size.height * 0.78), 140,
        Colors.white.withOpacity(0.035));

    // Cuadrícula sutil
    final gridPaint = Paint()
      ..color = Colors.white.withOpacity(0.055)
      ..strokeWidth = 0.7;
    const step = 55.0;
    for (double x = 0; x < size.width; x += step) {
      canvas.drawLine(Offset(x, 0), Offset(x, size.height), gridPaint);
    }
    for (double y = 0; y < size.height; y += step) {
      canvas.drawLine(Offset(0, y), Offset(size.width, y), gridPaint);
    }

    // Partículas flotantes
    final particles = List.generate(12, (i) {
      final x = (rng.nextDouble() * 0.82 + 0.09) * size.width;
      final baseY = (rng.nextDouble() * 0.82 + 0.09) * size.height;
      final speed = 0.6 + rng.nextDouble() * 1.4;
      final phase = rng.nextDouble() * 2 * pi;
      final y = baseY - 16 * sin(floatValue * pi * speed + phase).abs();
      final rot = 0.14 * sin(floatValue * pi * speed + phase);
      return (x, y, rot, rng.nextDouble(), i % 4);
    });

    for (final p in particles) {
      canvas.save();
      canvas.translate(p.$1, p.$2);
      canvas.rotate(p.$3);
      final opacity = 0.18 + 0.12 * p.$4;
      switch (p.$5) {
        case 0:
          _drawBulb(canvas, opacity, p.$4 * 5 + 14);
          break;
        case 1:
          _drawQuestionMark(canvas, opacity, p.$4 * 4 + 10);
          break;
        case 2:
          _drawSpeechBubble(canvas, opacity, p.$4 * 5 + 12);
          break;
        case 3:
          _drawDiamond(canvas, opacity, p.$4 * 4 + 8);
          break;
      }
      canvas.restore();
    }
  }

  void _drawBlob(Canvas canvas, Offset center, double radius, Color color) {
    canvas.drawCircle(center, radius, Paint()..color = color);
  }

  void _drawBulb(Canvas canvas, double opacity, double sz) {
    final fillPaint = Paint()
      ..color = Colors.white.withOpacity(opacity)
      ..style = PaintingStyle.fill;
    final strokePaint = Paint()
      ..color = Colors.white.withOpacity(opacity * 1.1)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 0.8;
    final basePaint = Paint()
      ..color = Colors.white.withOpacity(opacity * 0.85)
      ..style = PaintingStyle.fill
      ..strokeCap = StrokeCap.round;

    // Globe
    final globePath = Path()
      ..moveTo(-sz * 0.5, sz * 0.1)
      ..cubicTo(-sz * 0.5, -sz * 0.6, -sz * 0.3, -sz * 0.9, 0, -sz * 0.9)
      ..cubicTo(sz * 0.3, -sz * 0.9, sz * 0.5, -sz * 0.6, sz * 0.5, sz * 0.1)
      ..cubicTo(sz * 0.5, sz * 0.45, sz * 0.28, sz * 0.55, sz * 0.28, sz * 0.55)
      ..lineTo(-sz * 0.28, sz * 0.55)
      ..cubicTo(
          -sz * 0.28, sz * 0.55, -sz * 0.5, sz * 0.45, -sz * 0.5, sz * 0.1)
      ..close();
    canvas.drawPath(globePath, fillPaint);
    canvas.drawPath(globePath, strokePaint);

    // Base bands
    final band1 = RRect.fromRectAndRadius(
      Rect.fromCenter(
          center: Offset(0, sz * 0.65), width: sz * 0.7, height: sz * 0.14),
      const Radius.circular(3),
    );
    final band2 = RRect.fromRectAndRadius(
      Rect.fromCenter(
          center: Offset(0, sz * 0.8), width: sz * 0.58, height: sz * 0.13),
      const Radius.circular(3),
    );
    final band3 = RRect.fromRectAndRadius(
      Rect.fromCenter(
          center: Offset(0, sz * 0.94), width: sz * 0.46, height: sz * 0.12),
      const Radius.circular(3),
    );
    canvas.drawRRect(
        band1, basePaint..color = Colors.white.withOpacity(opacity * 0.85));
    canvas.drawRRect(
        band2, basePaint..color = Colors.white.withOpacity(opacity * 0.68));
    canvas.drawRRect(
        band3, basePaint..color = Colors.white.withOpacity(opacity * 0.5));

    // Filament hint
    final filPaint = Paint()
      ..color = Colors.white.withOpacity(opacity * 0.35)
      ..strokeWidth = 0.7
      ..style = PaintingStyle.stroke
      ..strokeCap = StrokeCap.round;
    canvas.drawLine(
        Offset(-sz * 0.18, sz * 0.05), Offset(sz * 0.18, sz * 0.05), filPaint);
  }

  void _drawQuestionMark(Canvas canvas, double opacity, double sz) {
    final paint = Paint()
      ..color = Colors.white.withOpacity(opacity)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.5
      ..strokeCap = StrokeCap.round;

    final path = Path()
      ..moveTo(-sz * 0.3, -sz * 0.55)
      ..cubicTo(-sz * 0.3, -sz * 0.9, sz * 0.5, -sz * 0.9, sz * 0.5, -sz * 0.4)
      ..cubicTo(sz * 0.5, -sz * 0.1, 0, -sz * 0.1, 0, sz * 0.2);
    canvas.drawPath(path, paint);
    canvas.drawCircle(
        Offset(0, sz * 0.55),
        sz * 0.12,
        Paint()
          ..color = Colors.white.withOpacity(opacity)
          ..style = PaintingStyle.fill);
  }

  void _drawSpeechBubble(Canvas canvas, double opacity, double sz) {
    final fillPaint = Paint()
      ..color = Colors.white.withOpacity(opacity)
      ..style = PaintingStyle.fill;
    final strokePaint = Paint()
      ..color = Colors.white.withOpacity(opacity * 1.1)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 0.8;
    final linePaint = Paint()
      ..color = Colors.white.withOpacity(opacity * 0.55)
      ..strokeWidth = 0.7
      ..strokeCap = StrokeCap.round
      ..style = PaintingStyle.stroke;

    final bubble = RRect.fromRectAndRadius(
      Rect.fromCenter(
          center: Offset(0, -sz * 0.15), width: sz * 1.6, height: sz * 1.0),
      Radius.circular(sz * 0.2),
    );
    canvas.drawRRect(bubble, fillPaint);
    canvas.drawRRect(bubble, strokePaint);

    // Tail
    final tail = Path()
      ..moveTo(-sz * 0.3, sz * 0.35)
      ..lineTo(-sz * 0.6, sz * 0.7)
      ..lineTo(sz * 0.1, sz * 0.35)
      ..close();
    canvas.drawPath(tail, fillPaint);
    canvas.drawPath(tail, strokePaint);

    // Lines inside
    canvas.drawLine(Offset(-sz * 0.55, -sz * 0.25),
        Offset(sz * 0.55, -sz * 0.25), linePaint);
    canvas.drawLine(
        Offset(-sz * 0.55, sz * 0.05), Offset(sz * 0.2, sz * 0.05), linePaint);
  }

  void _drawDiamond(Canvas canvas, double opacity, double sz) {
    final paint = Paint()
      ..color = Colors.white.withOpacity(opacity)
      ..style = PaintingStyle.fill;
    final stroke = Paint()
      ..color = Colors.white.withOpacity(opacity * 1.1)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 0.7;

    final path = Path()
      ..moveTo(0, -sz)
      ..lineTo(sz * 0.6, 0)
      ..lineTo(0, sz)
      ..lineTo(-sz * 0.6, 0)
      ..close();
    canvas.drawPath(path, paint);
    canvas.drawPath(path, stroke);
  }

  @override
  bool shouldRepaint(_BackgroundPainter old) =>
      old.floatValue != floatValue || old.bgValue != bgValue;
}

