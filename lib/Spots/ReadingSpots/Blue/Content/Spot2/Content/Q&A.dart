class _BulbIconPainter extends CustomPainter {
  @override
  void paint(Canvas canvas, Size size) {
    final w = size.width;
    final h = size.height;

    final fillPaint = Paint()
      ..color = Colors.white.withOpacity(0.92)
      ..style = PaintingStyle.fill;
    final basePaint = Paint()..style = PaintingStyle.fill;
    final filamentPaint = Paint()
      ..color = const Color(0xFF1E643C).withOpacity(0.35)
      ..style = PaintingStyle.stroke
      ..strokeWidth = 1.2
      ..strokeCap = StrokeCap.round;
    final shinePaint = Paint()
      ..color = Colors.white.withOpacity(0.25)
      ..style = PaintingStyle.fill;

    // Globe
    final globePath = Path()
      ..moveTo(w * 0.18, h * 0.52)
      ..cubicTo(w * 0.18, h * 0.62, w * 0.28, h * 0.66, w * 0.28, h * 0.66)
      ..lineTo(w * 0.72, h * 0.66)
      ..cubicTo(w * 0.72, h * 0.66, w * 0.82, h * 0.62, w * 0.82, h * 0.52)
      ..cubicTo(w * 0.82, h * 0.28, w * 0.68, h * 0.06, w * 0.5, h * 0.06)
      ..cubicTo(w * 0.32, h * 0.06, w * 0.18, h * 0.28, w * 0.18, h * 0.52)
      ..close();
    canvas.drawPath(globePath, fillPaint);

    // Glow circle behind
    canvas.drawCircle(
      Offset(w * 0.5, h * 0.36),
      w * 0.32,
      Paint()..color = Colors.white.withOpacity(0.07),
    );

    // Filament (decorative curve)
    final filPath = Path()
      ..moveTo(w * 0.32, h * 0.42)
      ..cubicTo(w * 0.38, h * 0.35, w * 0.44, h * 0.48, w * 0.5, h * 0.42)
      ..cubicTo(w * 0.56, h * 0.35, w * 0.62, h * 0.48, w * 0.68, h * 0.42);
    canvas.drawPath(filPath, filamentPaint);

    // Base band 1
    canvas.drawRRect(
      RRect.fromRectAndRadius(
        Rect.fromLTWH(w * 0.27, h * 0.67, w * 0.46, h * 0.08),
        const Radius.circular(3),
      ),
      basePaint..color = Colors.white.withOpacity(0.78),
    );
    // Base band 2
    canvas.drawRRect(
      RRect.fromRectAndRadius(
        Rect.fromLTWH(w * 0.3, h * 0.76, w * 0.4, h * 0.07),
        const Radius.circular(3),
      ),
      basePaint..color = Colors.white.withOpacity(0.6),
    );
    // Base band 3
    canvas.drawRRect(
      RRect.fromRectAndRadius(
        Rect.fromLTWH(w * 0.33, h * 0.84, w * 0.34, h * 0.07),
        const Radius.circular(3),
      ),
      basePaint..color = Colors.white.withOpacity(0.42),
    );

    // Shine
    canvas.save();
    canvas.rotate(-0.35);
    canvas.drawOval(
      Rect.fromCenter(
        center: Offset(w * 0.32, h * 0.22),
        width: w * 0.13,
        height: w * 0.28,
      ),
      shinePaint,
    );
    canvas.restore();
  }

  @override
  bool shouldRepaint(_BulbIconPainter old) => false;
}

